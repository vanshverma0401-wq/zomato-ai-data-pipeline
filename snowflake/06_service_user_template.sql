USE ROLE ACCOUNTADMIN;

CREATE USER IF NOT EXISTS ZOMATO_AIRFLOW_SVC
  TYPE = SERVICE
  LOGIN_NAME = 'ZOMATO_AIRFLOW_SVC'
  DEFAULT_ROLE = DBT_ROLE
  DEFAULT_SECONDARY_ROLES = ()
  DEFAULT_WAREHOUSE = ZOMATO_WH
  DEFAULT_NAMESPACE = 'ZOMATO.RAW';

GRANT ROLE DBT_ROLE TO USER ZOMATO_AIRFLOW_SVC;

ALTER USER ZOMATO_AIRFLOW_SVC
  SET RSA_PUBLIC_KEY = '<PUBLIC_KEY_BODY_WITHOUT_PEM_DELIMITERS>';

GRANT USAGE ON WAREHOUSE ZOMATO_WH TO ROLE DBT_ROLE;
GRANT USAGE ON DATABASE ZOMATO TO ROLE DBT_ROLE;
GRANT USAGE ON SCHEMA ZOMATO.RAW TO ROLE DBT_ROLE;
GRANT USAGE ON STAGE ZOMATO.RAW.ZOMATO_RAW_STAGE TO ROLE DBT_ROLE;
GRANT USAGE ON FILE FORMAT ZOMATO.RAW.CSV_FMT TO ROLE DBT_ROLE;
GRANT SELECT, INSERT ON ALL TABLES IN SCHEMA ZOMATO.RAW TO ROLE DBT_ROLE;
